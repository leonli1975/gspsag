"""M1: independent validation on a second network (PEGASE 1354), matching the
paper's operator style: a physical branch-susceptance graph (1/|z| for lines, a
fixed transformer weight), synthetic sags generated by the Zbus method, D-optimal
vs random vs max-degree placement, and fingerprint localization.
"""
import json
import os
import sys

import numpy as np
import networkx as nx
import scipy.sparse as sp
import pandapower as pp
import pandapower.networks as pn

BASE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, BASE)
from experiment_estimation_designed import greedy_d_optimal, gsp

OUT = os.path.join(BASE, 'results_second_network.json')
N_FOLDS = 5


def build_ybus(net):
    N = len(net.bus)
    Y = np.zeros((N, N), dtype=complex)
    for _, l in net.line.iterrows():
        u, v = int(l['from_bus']), int(l['to_bus'])
        z = l['r_ohm_per_km'] * l['length_km'] + 1j * l['x_ohm_per_km'] * l['length_km']
        if abs(z) < 1e-12:
            z = 1e-10
        y = 1.0 / z
        Y[u, v] -= y; Y[v, u] -= y; Y[u, u] += y; Y[v, v] += y
    for _, t in net.trafo.iterrows():
        u, v = int(t['hv_bus']), int(t['lv_bus'])
        y = 1.0 / (0.001 + 1j * 0.05)
        Y[u, v] -= y; Y[v, u] -= y; Y[u, u] += y; Y[v, v] += y
    Y[0, 0] += 1.0 / (0.01 + 1j * 0.1)
    return Y


def gen_events(Zbus, n_events=120):
    N = Zbus.shape[0]
    fbs = np.linspace(0, N - 1, n_events).astype(int)
    types = ['3ph', '2ph', '1ph']; rfs = [0.01, 0.05, 0.1, 0.5]
    ev = []
    for k, f in enumerate(fbs):
        ft = types[k % 3]; rf = rfs[(k // 3) % 4]
        zkk = Zbus[f, f]
        ztot = {'3ph': zkk + rf, '2ph': 2 * (zkk + rf), '1ph': 3 * (zkk + rf)}[ft]
        V = np.abs(1.0 - Zbus[:, f] / ztot)
        ev.append((V, int(f)))
    return ev


def build_operator(net):
    """Branch-susceptance graph: 1/|z| for lines, fixed transformer weight."""
    N = len(net.bus)
    G = nx.Graph(); G.add_nodes_from(range(N))
    for _, l in net.line.iterrows():
        u, v = int(l['from_bus']), int(l['to_bus'])
        z = np.hypot(l['r_ohm_per_km'] * l['length_km'], l['x_ohm_per_km'] * l['length_km'])
        G.add_edge(u, v, weight=1.0 / max(z, 1e-6))
    for _, t in net.trafo.iterrows():
        G.add_edge(int(t['hv_bus']), int(t['lv_bus']), weight=50.0)
    W = nx.adjacency_matrix(G, weight='weight').astype(np.float64)
    L = sp.diags(np.asarray(W.sum(1)).ravel()) - W
    return G, W, L


def idw_recon(dist, S, v, N):
    d = dist[:, S]
    w = 1.0 / (d ** 2 + 1e-12)
    return (w @ v[S]) / w.sum(1)


def hop_graph(net):
    G = nx.Graph(); G.add_nodes_from(range(len(net.bus)))
    for _, l in net.line.iterrows():
        G.add_edge(int(l['from_bus']), int(l['to_bus']))
    for _, t in net.trafo.iterrows():
        G.add_edge(int(t['hv_bus']), int(t['lv_bus']))
    return G


def loc_eval(patterns, fault, hop, S, N):
    rng = np.random.RandomState(0)
    order = rng.permutation(len(fault)); folds = np.array_split(order, N_FOLDS)
    le1, le3, vis = [], [], []
    for k in range(N_FOLDS):
        test = folds[k]; train = np.concatenate([folds[j] for j in range(N_FOLDS) if j != k])
        db = np.unique(fault[train]); Dm = np.zeros((N, len(db)))
        for c, b in enumerate(db):
            Dm[:, c] = patterns[train[fault[train] == b]].mean(0)
        DmS = Dm[S, :]; DmSn = DmS / (np.linalg.norm(DmS, axis=0, keepdims=True) + 1e-12)
        for ti in test:
            y = patterns[ti, S]; yn = y / (np.linalg.norm(y) + 1e-12)
            sim = DmSn.T @ yn; pred = db[int(np.argmax(sim))]
            e = hop[pred].get(fault[ti], 999)
            le1.append(e <= 1); le3.append(e <= 3)
            vis.append(min(hop[fault[ti]][s] for s in S) <= 2)
    return float(np.mean(le1)), float(np.mean(le3)), float(np.mean(vis))


def main():
    net = pn.case1354pegase()
    pp.create_ext_grid(net, bus=0, vm_pu=1.0)
    Z = np.linalg.pinv(build_ybus(net))
    N = Z.shape[0]
    G, W, L = build_operator(net)
    print('N', N, 'edges', G.number_of_edges())

    # largest connected component of the operator graph
    cc = max(nx.connected_components(G), key=len)
    if len(cc) < N:
        nodes = sorted(cc); rel = {o: n for n, o in enumerate(nodes)}
        G = nx.relabel_nodes(G.subgraph(cc).copy(), rel)
        N = len(nodes)
        W = nx.adjacency_matrix(G, weight='weight').astype(np.float64)
        L = sp.diags(np.asarray(W.sum(1)).ravel()) - W
        print('CC', N)

    vals, U = np.linalg.eigh(L.toarray())
    ev = gen_events(Z, 120)
    patterns = np.array([1.0 - v for v, f in ev]); fault = np.array([min(f, N - 1) for v, f in ev])

    Gdev = U.T @ patterns.T; e = Gdev ** 2
    cum = np.cumsum(e, axis=0) / e.sum(0, keepdims=True)
    band = {k: float(np.mean(cum[k - 1]) * 100) for k in [1, 5, 10]}

    Gh = hop_graph(net)
    if len(cc) < len(net.bus):
        Gh = nx.relabel_nodes(Gh.subgraph(cc).copy(), rel)
    hop = dict(nx.all_pairs_shortest_path_length(Gh))
    dist = np.full((N, N), 1e6)
    for i, di in nx.all_pairs_dijkstra_path_length(G, weight='weight'):
        for j, d in di.items():
            dist[i, j] = d
    deg = np.array([Gh.degree(i) for i in range(N)])

    out = {'N': N, 'band': band, 'n_events': len(ev), 'by_M': {}}
    for M in [30, 100]:
        B = min(M // 3, 50)
        Sdes = greedy_d_optimal(U, B, M)
        Smd = np.argsort(-deg)[:M]
        rand = [np.random.RandomState(t).choice(N, M, replace=False) for t in range(8)]
        row = {}
        for name, S in [('designed', Sdes), ('maxdegree', Smd)]:
            rmse = float(np.mean([np.sqrt(np.mean((gsp(U, v, S, B) - v) ** 2)) for v, f in ev]))
            l1, l3, cov = loc_eval(patterns, fault, hop, S, N)
            row[name] = {'est': rmse, 'le1': l1, 'le3': l3, 'cov': cov}
        rr = []
        for S in rand:
            rmse = float(np.mean([np.sqrt(np.mean((gsp(U, v, S, B) - v) ** 2)) for v, f in ev]))
            l1, l3, cov = loc_eval(patterns, fault, hop, S, N)
            rr.append({'est': rmse, 'le1': l1, 'le3': l3, 'cov': cov})
        row['random'] = {k: float(np.mean([x[k] for x in rr])) for k in rr[0]}
        row['idw'] = {'est': float(np.mean([np.sqrt(np.mean((idw_recon(dist, rand[0], v, N) - v) ** 2)) for v, f in ev]))}
        out['by_M'][M] = {'B': B, 'placements': row}
        print(f'M={M} B={B}')
        for name in ['designed', 'maxdegree', 'random']:
            r = row[name]
            print(f"  {name:9s} est={r['est']:.3f} le1={r['le1']*100:5.1f}% le3={r['le3']*100:5.1f}% cov={r['cov']*100:5.1f}%")
        print(f"  IDW(rand) est={row['idw']['est']:.3f}")
    with open(OUT, 'w') as f:
        json.dump(out, f, indent=2)
    print('saved', OUT)


if __name__ == '__main__':
    main()
